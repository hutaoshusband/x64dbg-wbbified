#!/usr/bin/env python3
"""Generate src/gui/Src/Utils/WebLinks.h with XOR-obfuscated external URLs.

Keeps functional web links working without plaintext URL strings in the
binary image. Run from the repository root (x64dbg/).
"""
import sys

KEY = 0x5A

URLS = {
    "website": "https://x64dbg.com",
    "help": "https://help.x64dbg.com",
    "blog": "https://blog.x64dbg.com",
    "donate": "https://donate.x64dbg.com",
    "faq": "https://faq.x64dbg.com",
    "report": "https://report.x64dbg.com",
    "plugins": "https://plugins.x64dbg.com",
    "conditionalBreakpointHelp": "https://help.x64dbg.com/en/latest/introduction/ConditionalBreakpoint.html",
    "conditionalTracingHelp": "https://help.x64dbg.com/en/latest/introduction/ConditionalTracing.html",
}

def c_array(data):
    return ", ".join("0x%02X" % (b ^ KEY) for b in data)

header = """#pragma once

// Auto-generated by gen_weblinks.py -- do not edit by hand.
// External URLs stored XOR-encoded so no plaintext URL remains in the binary.

#include <QString>

namespace WebLinks
{
    inline QString decode(const unsigned char* data, int size)
    {
        QString result;
        result.reserve(size);
        for(int i = 0; i < size; i++)
            result += QChar(char(data[i] ^ 0x%02X));
        return result;
    }

""" % KEY

for name, url in URLS.items():
    data = url.encode("ascii")
    header += "    inline QString %s() { static const unsigned char e[] = { %s }; return decode(e, %d); }\n\n" % (name, c_array(data), len(data))

header += "}\n"

with open("src/gui/Src/Utils/WebLinks.h", "w", newline="\n") as f:
    f.write(header)
print("wrote src/gui/Src/Utils/WebLinks.h (%d urls)" % len(URLS))
